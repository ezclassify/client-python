#!/usr/bin/env python3
"""Regenerate THIRD-PARTY-NOTICES.md from the packages' declared dependencies.

Run this with a Python environment that has the two published packages
installed (any install mode works, editable included):

    python scripts/gen-notices.py            # writes THIRD-PARTY-NOTICES.md
    python scripts/gen-notices.py --check    # exits 1 if the file is stale

The direct runtime dependency set is read live from each package's installed
metadata (Requires-Dist), and each dependency's license identifier is read
live from its installed distribution, so the committed file cannot silently
drift from the source of truth. CI regenerates and diffs on every run.

Copyright attributions for known dependencies come from a curated map inside
this script rather than from parsing upstream LICENSE files, because upstream
year-range bumps would otherwise churn this file on every dependency release.
A new direct dependency falls back to a best-effort extraction from its
installed license file; review that line when it first appears.

The transitive closure is intentionally not tabulated here. It is enforced in
CI by a pip-licenses allowlist over a clean production install, and the exact
resolved inventory ships in the per-build CycloneDX SBOM artifact.
"""

from __future__ import annotations

import argparse
import re
import sys
from importlib import metadata
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
NOTICES_PATH = REPO_ROOT / "THIRD-PARTY-NOTICES.md"

# The packages published to PyPI from this repository, in the order their
# sections appear in the notices file. Maps package name to source directory.
PUBLISHED_PACKAGES = {
    "ezclassify-rest-contract": "types/",
    "ezclassify-rest-client": "client/",
}

# Stable copyright attributions, keyed by canonical (PEP 503) name. Curated
# so upstream copyright-year bumps do not fail the CI staleness diff; update
# an entry only when the holder actually changes.
COPYRIGHT_OVERRIDES = {
    "pydantic": (
        "Copyright (c) 2017 to present Pydantic Services Inc. "
        "and individual contributors"
    ),
    "typing-extensions": "Copyright (c) Python Software Foundation",
    "httpcore": "Copyright (c) 2020, Encode OSS Ltd",
    "httpx": "Copyright (c) 2019, Encode OSS Ltd",
}

PREAMBLE = """\
# Third-Party Notices

This file lists the direct third-party runtime dependencies of the EzClassify
Python packages published to PyPI, together with their license identifiers and
upstream copyright holders.

Two packages are published from this repository:

- `ezclassify-rest-contract` (directory `types/`)
- `ezclassify-rest-client` (directory `client/`)

The top-level `ezclassify` package (repository root) is a dev-only integration
harness marked `Private :: Do Not Upload`; it is not published and its only
direct dependencies are the first-party packages above, so it is not covered
here.

Each dependency keeps its own license; this file does not relicense any of it.

Transitive dependencies are not tabulated here. CI checks the full resolved
production closure against a license allowlist (pip-licenses) on every run,
and the exact pinned inventory of each build is published as a CycloneDX SBOM
workflow artifact.

---
"""

LICENSE_NOTES = """\
---

## License notes

All direct runtime dependencies are permissive (MIT / BSD-3-Clause / PSF-2.0).
Identifiers outside the literal MIT/ISC/BSD/UPL/Apache set, including two that
only appear in the transitive closure, are called out below:

- **typing-extensions** is licensed PSF-2.0 (Python Software Foundation
  License). PSF-2.0 is a permissive, BSD-style, non-copyleft license. It is not
  one of the literal MIT/ISC/BSD/UPL/Apache identifiers but imposes no copyleft
  obligation.

- **certifi** (transitive, pulled in by `httpx`) is licensed MPL-2.0 (Mozilla
  Public License 2.0). MPL-2.0 is a file-level weak-copyleft license, not a
  permissive one, and is therefore outside the MIT/ISC/BSD/UPL/Apache set.
  certifi is a pure data package: it ships Mozilla's root CA certificate bundle
  and a thin accessor. It is consumed unmodified as an installed wheel and is
  not vendored or rebuilt, so the file-level copyleft obligation (disclose
  source of modified MPL files) is not triggered by our distribution. The CI
  license gate allows MPL-2.0 for certifi only; if a strict permissive-only
  posture is required, pin httpx with a CA bundle override or supply
  certificates via the OS trust store.

- **sniffio** is an optional/transitive dependency of `anyio` on some Python
  versions; it is dual-licensed MIT or Apache-2.0, both permissive.

---

Generated by `scripts/gen-notices.py` (run `make notices`). Do not edit by
hand; hand edits are overwritten on the next regeneration and fail the CI
staleness check.
"""


def canonical(name: str) -> str:
    """Return the PEP 503 canonical form of a distribution name."""
    return re.sub(r"[-_.]+", "-", name).lower()


def direct_runtime_deps(package: str) -> list[tuple[str, str]]:
    """Return (canonical name, requirement spec) for a package's runtime deps.

    Reads Requires-Dist from the installed distribution and drops extras
    (dev/test requirements carry an `extra == ...` marker).

    Args:
        package: Published package name as installed.

    Returns:
        Sorted list of (canonical dependency name, declared version spec).

    Raises:
        importlib.metadata.PackageNotFoundError: If the package is not
            installed in the running interpreter's environment.
    """
    deps = []
    for req in metadata.requires(package) or []:
        if "extra ==" in req:
            continue
        m = re.match(r"^([A-Za-z0-9._-]+)\s*(.*)$", req.split(";")[0].strip())
        if m:
            deps.append((canonical(m.group(1)), m.group(2).strip()))
    return sorted(deps)


def license_id(dist: metadata.Distribution) -> str:
    """Return the best available license identifier for a distribution.

    Prefers the PEP 639 License-Expression field, then the legacy License
    field when it is a short identifier, then the trove license classifier.
    """
    md = dist.metadata
    expr = md.get("License-Expression")
    if expr:
        return expr
    lic = md.get("License")
    if lic and len(lic) < 60 and "\n" not in lic:
        return lic
    for classifier in md.get_all("Classifier") or []:
        if classifier.startswith("License ::"):
            return classifier.split("::")[-1].strip()
    return "UNKNOWN (review upstream metadata)"


def copyright_line(dist: metadata.Distribution, name: str) -> str:
    """Return the copyright attribution for a distribution.

    Uses the curated override map first; otherwise takes the first line of
    the installed license file that starts with "Copyright". The fallback is
    best effort and should be reviewed (and promoted to the override map)
    when a new direct dependency first appears.
    """
    if name in COPYRIGHT_OVERRIDES:
        return COPYRIGHT_OVERRIDES[name]
    for f in dist.files or []:
        base = Path(str(f)).name.upper()
        if base.startswith(("LICENSE", "COPYING", "NOTICE")):
            try:
                text = f.read_text()
            except (OSError, UnicodeDecodeError):
                continue
            for line in text.splitlines():
                stripped = line.strip()
                if stripped.lower().startswith("copyright"):
                    # Normalize markdown links and the copyright sign so the
                    # table stays plain ASCII.
                    stripped = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", stripped)
                    return stripped.replace("©", "(c)").rstrip(".")
    return "(see upstream LICENSE file)"


def build_section(package: str, directory: str) -> str:
    """Render the notices section for one published package."""
    lines = [f"## {package}", ""]
    dist_names = []
    rows = []
    siblings = []
    for dep, spec in direct_runtime_deps(package):
        if dep in {canonical(p) for p in PUBLISHED_PACKAGES}:
            siblings.append(dep)
            continue
        dist = metadata.distribution(dep)
        display = dist.metadata["Name"]
        dist_names.append(f"`{display}`")
        spec_txt = f" ({spec})" if spec else ""
        rows.append(
            f"| {display}{spec_txt} | {license_id(dist)} "
            f"| {copyright_line(dist, dep)} |"
        )
    dep_list = ", ".join(dist_names) if dist_names else "none"
    lines.append(f"Directory `{directory}`. Direct runtime dependencies: {dep_list}.")
    if siblings:
        lines.append(
            "Also depends on the sibling packages "
            + ", ".join(f"`{s}`" for s in sorted(siblings))
            + " (covered above)."
        )
    lines.append("")
    if rows:
        lines.append("| Package (declared requirement) | License | Copyright |")
        lines.append("| --- | --- | --- |")
        lines.extend(rows)
        lines.append("")
    return "\n".join(lines)


def render() -> str:
    """Render the full THIRD-PARTY-NOTICES.md content."""
    sections = [
        build_section(pkg, directory) for pkg, directory in PUBLISHED_PACKAGES.items()
    ]
    return PREAMBLE + "\n" + "\n".join(sections) + "\n" + LICENSE_NOTES


def main() -> int:
    """CLI entry point. Returns the process exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed file matches; do not write",
    )
    args = parser.parse_args()

    content = render()
    if args.check:
        current = NOTICES_PATH.read_text() if NOTICES_PATH.exists() else ""
        if current != content:
            sys.stderr.write(
                "THIRD-PARTY-NOTICES.md is stale. "
                "Run 'make notices' and commit the result.\n"
            )
            return 1
        print("THIRD-PARTY-NOTICES.md is current.")
        return 0

    NOTICES_PATH.write_text(content)
    print(f"Wrote {NOTICES_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
