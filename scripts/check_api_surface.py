"""1.0 public API surface golden for the published EzClassify Python packages.

The exported API of every package this repo ships to PyPI is frozen at 1.0:

    ezclassify-rest-contract    (types/ezclassify_rest_contract)
    ezclassify-rest-client   (client/ezclassify_rest_client)

This script parses the package sources with ``ast`` (no imports, no installed
environment needed) and emits a deterministic text dump of the public surface:
module ``__all__`` lists, public classes with their bases, fields, and method
signatures (a public member inherited from a private base, in this module or
in a private module it imports, is listed on the subclass that publishes it),
public module-level functions, and public constants. Names are sorted, docstrings and comments never appear,
and annotation/default text is taken verbatim from the source with whitespace
collapsed, so the dump is byte-identical across Python versions.

Modes:
    python3 scripts/check_api_surface.py --check   diff against api-surface.txt
                                                   (default; CI runs this)
    python3 scripts/check_api_surface.py --write   regenerate api-surface.txt
                                                   (or: make api-surface)

A ``--check`` failure means the public API changed. If the change is a
reviewed, deliberate API change, regenerate the golden and commit it together
with the code change. Private names and private modules are excluded. The
generated production ``models.py`` is included because it is the API users
actually import.
"""

from __future__ import annotations

import argparse
import ast
import difflib
import sys
from pathlib import Path
from typing import List, Tuple

REPO_ROOT = Path(__file__).resolve().parent.parent
GOLDEN_PATH = REPO_ROOT / "api-surface.txt"
REGEN_COMMAND = "make api-surface"

# Every package published to PyPI at 1.0. The repo-root "ezclassify" package
# is a dev-only harness (Private :: Do Not Upload) and is intentionally absent.
PACKAGES: List[Tuple[str, str]] = [
    ("ezclassify-rest-contract", "types/ezclassify_rest_contract"),
    ("ezclassify-rest-client", "client/ezclassify_rest_client"),
]

HEADER = f"""\
# EzClassify Python SDK public API surface, frozen at 1.0.
# Reviewed contract for every package published to PyPI from this repo:
# exported names, class bases, fields, and callable signatures, including the
# public members a class inherits from a private base, whether that base is
# declared in the same module or in a private module the module imports.
# CI diffs the live sources against this file and fails on any drift.
# Generated by scripts/check_api_surface.py. Do not edit by hand.
# To change the public API deliberately, regenerate with: {REGEN_COMMAND}
"""

Entry = Tuple[str, List[str]]
# A private base class paired with the source text it was parsed from.
PrivateBase = Tuple[str, ast.ClassDef]


def _seg(source: str, node: ast.AST) -> str:
    """Return the source text of a node with all whitespace collapsed."""
    text = ast.get_source_segment(source, node)
    if text is None:
        return "<unrepresentable>"
    return " ".join(text.split())


def _is_public_method(name: str) -> bool:
    """Public methods plus dunders like __init__; single-underscore is private."""
    if not name.startswith("_"):
        return True
    return name.startswith("__") and name.endswith("__") and len(name) > 4


def _format_arguments(source: str, args: ast.arguments) -> str:
    parts: List[str] = []

    def fmt(arg: ast.arg, default: "ast.expr | None") -> str:
        text = arg.arg
        if arg.annotation is not None:
            text += f": {_seg(source, arg.annotation)}"
        if default is not None:
            text += f" = {_seg(source, default)}"
        return text

    positional = list(args.posonlyargs) + list(args.args)
    defaults: List["ast.expr | None"] = [None] * (
        len(positional) - len(args.defaults)
    ) + list(args.defaults)
    for arg, default in zip(positional, defaults):
        parts.append(fmt(arg, default))
        if args.posonlyargs and arg is args.posonlyargs[-1]:
            parts.append("/")

    if args.vararg is not None:
        parts.append("*" + fmt(args.vararg, None))
    elif args.kwonlyargs:
        parts.append("*")
    for arg, default in zip(args.kwonlyargs, args.kw_defaults):
        parts.append(fmt(arg, default))
    if args.kwarg is not None:
        parts.append("**" + fmt(args.kwarg, None))
    return ", ".join(parts)


def _format_function(
    source: str, node: "ast.FunctionDef | ast.AsyncFunctionDef"
) -> str:
    decorators = "".join(f"@{_seg(source, d)} " for d in node.decorator_list)
    keyword = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
    returns = f" -> {_seg(source, node.returns)}" if node.returns is not None else ""
    return (
        f"{decorators}{keyword} {node.name}"
        f"({_format_arguments(source, node.args)}){returns}"
    )


def _format_all(source: str, value: ast.expr) -> str:
    if isinstance(value, (ast.List, ast.Tuple)):
        names = sorted(
            elt.value
            for elt in value.elts
            if isinstance(elt, ast.Constant) and isinstance(elt.value, str)
        )
        return "__all__ = [" + ", ".join(names) + "]"
    return f"__all__ = {_seg(source, value)}"


def _private_classes(source: str, tree: ast.Module) -> "dict[str, PrivateBase]":
    """Index one module's private classes by name, paired with its source."""
    return {
        stmt.name: (source, stmt)
        for stmt in tree.body
        if isinstance(stmt, ast.ClassDef) and stmt.name.startswith("_")
    }


def _package_root(path: Path) -> Path:
    """Return the top-most directory of the package ``path`` belongs to."""
    root = path.parent
    while (root.parent / "__init__.py").is_file():
        root = root.parent
    return root


def _imported_module_path(path: Path, node: ast.ImportFrom) -> "Path | None":
    """Resolve ``from ... import ...`` to a module file inside this package.

    Only imports that land on a file within the same package are resolved;
    anything else (third-party, stdlib) has no private base worth reading.
    """
    if node.module is None:
        return None
    parts = node.module.split(".")
    if node.level:
        try:
            base = path.parents[node.level - 1]
        except IndexError:
            return None
    else:
        root = _package_root(path)
        if parts[0] != root.name:
            return None
        base, parts = root.parent, parts
    candidate = base.joinpath(*parts)
    for target in (candidate.with_suffix(".py"), candidate / "__init__.py"):
        if target.is_file():
            return target
    return None


def _private_bases(
    source: str, tree: ast.Module, path: Path
) -> "dict[str, PrivateBase]":
    """Index the private classes a module's public classes can inherit from.

    A public class that inherits from a private base still publishes the base's
    public methods and properties, so the dump has to read them out of the base
    or it reports a smaller surface than the package actually ships, and drift
    inside the base goes unnoticed.

    The bases are not always local. The generated ``models.py`` takes every one
    of its ``from_dict`` decoders from ``_model_helpers``, and a same-module
    index would miss all of them and leave those signatures outside the frozen
    contract. Private modules this one imports from are parsed too, and
    each base is carried with the source text it came from so its members are
    rendered from the right file.
    """
    bases: "dict[str, PrivateBase]" = {}
    for stmt in tree.body:
        if not isinstance(stmt, ast.ImportFrom):
            continue
        target = _imported_module_path(path, stmt)
        if target is None or target == path:
            continue
        sibling_source = target.read_text(encoding="utf-8")
        sibling_tree = ast.parse(sibling_source, filename=str(target))
        bases.update(_private_classes(sibling_source, sibling_tree))
    # A private class declared here wins over an imported name of the same
    # spelling, exactly as the module namespace resolves it.
    bases.update(_private_classes(source, tree))
    return bases


def _format_class(
    source: str,
    node: ast.ClassDef,
    private_bases: "dict[str, PrivateBase] | None" = None,
) -> List[str]:
    private_bases = private_bases or {}
    bases = [_seg(source, b) for b in node.bases]
    bases += [f"{kw.arg}={_seg(source, kw.value)}" for kw in node.keywords]
    decorators = "".join(f"@{_seg(source, d)} " for d in node.decorator_list)
    header = f"{decorators}class {node.name}"
    if bases:
        header += f"({', '.join(bases)})"

    # A name declared more than once, as @overload signatures ahead of the
    # implementation, publishes every declaration: the overloads are the
    # signatures a type checker holds callers to.
    members: "dict[str, List[str]]" = {}
    for name, member_lines in _collect_entries(source, node.body, module_level=False):
        members.setdefault(name, []).extend(member_lines)
    # Walk private bases outward, nearest first; a name already declared on the
    # subclass overrides the inherited one, exactly as Python resolves it.
    queue = [name for name in bases if name in private_bases]
    seen = set(queue)
    while queue:
        base_source, base = private_bases[queue.pop(0)]
        for name, member_lines in _collect_entries(
            base_source, base.body, module_level=False
        ):
            members.setdefault(name, member_lines)
        for grandparent in (_seg(base_source, b) for b in base.bases):
            if grandparent in private_bases and grandparent not in seen:
                seen.add(grandparent)
                queue.append(grandparent)

    lines = [header]
    for _, member_lines in sorted(members.items(), key=lambda e: e[0]):
        lines.extend("  " + line for line in member_lines)
    return lines


def _collect_entries(
    source: str,
    body: List[ast.stmt],
    module_level: bool,
    private_bases: "dict[str, PrivateBase] | None" = None,
) -> List[Entry]:
    entries: List[Entry] = []
    for stmt in body:
        if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef)):
            # Module-level dunders are metadata, not API; class dunders such
            # as __init__ and __enter__ are contract and stay in the dump.
            public = (
                not stmt.name.startswith("_")
                if module_level
                else _is_public_method(stmt.name)
            )
            if public:
                entries.append((stmt.name, [_format_function(source, stmt)]))
        elif isinstance(stmt, ast.ClassDef):
            if not stmt.name.startswith("_"):
                entries.append((stmt.name, _format_class(source, stmt, private_bases)))
        elif isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
            name = stmt.target.id
            if not name.startswith("_"):
                line = f"{name}: {_seg(source, stmt.annotation)}"
                if stmt.value is not None:
                    line += f" = {_seg(source, stmt.value)}"
                entries.append((name, [line]))
        elif isinstance(stmt, ast.Assign):
            for target in stmt.targets:
                if not isinstance(target, ast.Name):
                    continue
                if target.id == "__all__" and module_level:
                    entries.append((target.id, [_format_all(source, stmt.value)]))
                elif not target.id.startswith("_"):
                    entries.append(
                        (target.id, [f"{target.id} = {_seg(source, stmt.value)}"])
                    )
        elif isinstance(stmt, (ast.Try, ast.If)) and module_level:
            # Compatibility blocks (try/except ImportError, if TYPE_CHECKING)
            # can still define public names; walk every branch.
            branches = [stmt.body, getattr(stmt, "orelse", [])]
            branches += [h.body for h in getattr(stmt, "handlers", [])]
            branches.append(getattr(stmt, "finalbody", []))
            for branch in branches:
                entries.extend(_collect_entries(source, branch, True, private_bases))
    return entries


def _iter_modules(package_dir: Path) -> List[Tuple[str, Path]]:
    """Yield (dotted_module_name, path) for the package's public modules."""
    modules: List[Tuple[str, Path]] = []
    for path in sorted(package_dir.rglob("*.py")):
        rel = path.relative_to(package_dir.parent)
        stem = rel.stem
        # Skip private modules and filenames that are not importable modules.
        if stem != "__init__" and (stem.startswith("_") or not stem.isidentifier()):
            continue
        if any(part.startswith("_") for part in rel.parts[:-1]):
            continue
        dotted_parts = list(rel.parts[:-1]) + ([] if stem == "__init__" else [stem])
        modules.append((".".join(dotted_parts), path))
    return sorted(modules)


def build_surface() -> str:
    """Render the full public surface dump for all published packages."""
    out: List[str] = [HEADER]
    for dist_name, rel_dir in PACKAGES:
        package_dir = REPO_ROOT / rel_dir
        if not package_dir.is_dir():
            raise SystemExit(f"ERROR: package directory not found: {rel_dir}")
        out.append(f"package {dist_name} ({rel_dir})")
        out.append("")
        for module_name, path in _iter_modules(package_dir):
            source = path.read_text(encoding="utf-8")
            tree = ast.parse(source, filename=str(path))
            out.append(f"module {module_name}")
            entries = sorted(
                _collect_entries(
                    source, tree.body, True, _private_bases(source, tree, path)
                ),
                key=lambda e: e[0],
            )
            for _, lines in entries:
                out.extend("  " + line for line in lines)
            out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check",
        action="store_true",
        help="diff the live surface against api-surface.txt (default)",
    )
    mode.add_argument(
        "--write",
        action="store_true",
        help="regenerate api-surface.txt from the live sources",
    )
    args = parser.parse_args()

    current = build_surface()

    if args.write:
        GOLDEN_PATH.write_text(current, encoding="utf-8")
        print(f"Wrote {GOLDEN_PATH.relative_to(REPO_ROOT)}")
        print("Review the diff and commit it together with the API change.")
        return 0

    if not GOLDEN_PATH.is_file():
        print(f"ERROR: {GOLDEN_PATH.name} is missing.", file=sys.stderr)
        print(f"Generate it with: {REGEN_COMMAND}", file=sys.stderr)
        return 1

    golden = GOLDEN_PATH.read_text(encoding="utf-8")
    if current == golden:
        print(f"Public API surface matches {GOLDEN_PATH.name} (1.0 contract intact).")
        return 0

    diff = difflib.unified_diff(
        golden.splitlines(),
        current.splitlines(),
        fromfile=f"{GOLDEN_PATH.name} (reviewed 1.0 contract)",
        tofile="current sources",
        lineterm="",
    )
    print("ERROR: public API surface drift detected.", file=sys.stderr)
    print(
        "The exported API of the published packages is a 1.0-locked contract\n"
        f"and no longer matches {GOLDEN_PATH.name}:\n",
        file=sys.stderr,
    )
    for line in diff:
        print(line, file=sys.stderr)
    print(
        "\nIf this is a reviewed, deliberate API change, regenerate the golden\n"
        f"and commit it together with the code change: {REGEN_COMMAND}",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
